"""Rebuild small, licensed UI fonts; normal web builds use the checked-in output."""
from pathlib import Path
import json

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'web-client/assets/fonts'


def cjk(code):
    return 0x2E80 <= code <= 0x9FFF or 0xF900 <= code <= 0xFAFF or 0xFF00 <= code <= 0xFFEF or 0x20000 <= code <= 0x323AF


def generate(source, target, characters, family):
    font = TTFont(FONTS / source)
    options = subset.Options()
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=characters & set(font.getBestCmap()))
    sub.subset(font)
    # Preserve copyright/license records and rename the derived font family.
    names = {1: family, 2: 'Regular', 3: family + '-Regular', 4: family + ' Regular',
             6: family + '-Regular', 16: family, 17: 'Regular'}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    font.save(FONTS / target)
    return set(font.getBestCmap())


def main():
    ui = set()
    paths = [ROOT / 'web-client/assets/copy.json', ROOT.parent / 'TH/backend/content/birth-regions.json']
    paths += [p for p in (ROOT / 'web-client/lib').rglob('*.dart') if p.name != 'chinese_coverage.dart']
    for path in paths:
        ui.update(map(ord, path.read_text(encoding='utf8')))
    common = set(ui)
    common.update(map(ord, (ROOT / 'scripts/fonts/location-characters.txt').read_text(encoding='utf8')))
    for lead in range(0xB0, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                common.update(map(ord, bytes([lead, trail]).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    coverage = set(TTFont(FONTS / 'NotoSansSC-Regular.otf').getBestCmap())
    initial = generate('NotoSansSC-Regular.otf', 'FateChineseUI.otf', ui & coverage, 'FateChineseUI')
    extended = generate('NotoSansSC-Regular.otf', 'FateChineseCommon.otf', (common & coverage) - initial, 'FateChineseCommon')
    generate('NotoSansSymbols-Regular.ttf', 'FateSymbols.ttf', ui, 'FateSymbols')
    generate('NotoSansSymbols2-Regular.ttf', 'FateSymbols2.ttf', ui, 'FateSymbols2')
    rows = ['// Generated by scripts/prepare-fonts.py. Keep the source font licenses.', '']
    for name, codes in [('chineseUiCharacters', initial), ('chineseCommonCharacters', initial | extended)]:
        chars = ''.join(chr(c) for c in sorted(codes) if cjk(c))
        rows.append('const ' + name + ' =')
        rows += ["    r'" + chars[i:i + 80] + "'" for i in range(0, len(chars), 80)]
        rows[-1] += ';'
        rows.append('')
    (ROOT / 'web-client/lib/ui/chinese_coverage.dart').write_text('\n'.join(rows), encoding='utf8')
    sizes = {name: (FONTS / name).stat().st_size for name in ['FateChineseUI.otf', 'FateChineseCommon.otf', 'FateSymbols.ttf', 'FateSymbols2.ttf']}
    if sizes['FateChineseUI.otf'] > 450_000 or sizes['FateSymbols.ttf'] + sizes['FateSymbols2.ttf'] > 50_000:
        raise RuntimeError('Startup font size budget exceeded')
    (FONTS / 'subsets.json').write_text(json.dumps({'ui': ''.join(chr(c) for c in sorted(initial)), 'bytes': sizes}, ensure_ascii=False), encoding='utf8')
    print(json.dumps({'font_bytes': sizes, 'startup_chinese_glyphs': len(initial), 'common_chinese_glyphs': len(initial | extended)}))


if __name__ == '__main__':
    main()
