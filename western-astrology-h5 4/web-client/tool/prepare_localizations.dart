import 'dart:convert';
import 'dart:io';
import 'dart:isolate';
import 'package:intl/date_symbol_data_local.dart';
import 'package:intl/date_time_patterns.dart';

// Run after updating intl: dart run tool/prepare_localizations.dart.
Future<void> main() async {
  const languages = [
    'th',
    'zh',
    'en_US',
  ]; // Keep Intl's default date formatter.
  final symbols = dateTimeSymbolMap();
  final patterns = dateTimePatternMap();
  final intlUri = await Isolate.resolvePackageUri(
    Uri.parse('package:intl/intl.dart'),
  );
  final license = await File.fromUri(
    intlUri!.resolve('../LICENSE'),
  ).readAsString();
  String literal(Object value) => const JsonEncoder.withIndent('  ')
      .convert(value)
      .replaceAll(r'$', r'\$')
      .replaceAllMapped(
        RegExp(r'[^\x00-\x7f]'),
        (match) =>
            '\\u${match[0]!.codeUnitAt(0).toRadixString(16).padLeft(4, '0')}',
      );
  final output = StringBuffer()
    ..writeln(
      '// Generated by tool/prepare_localizations.dart from the installed intl package.',
    )
    ..writeln('// Regenerate when updating intl; retain its license below.')
    ..writeln(license.trim().split('\n').map((line) => '// $line').join('\n'))
    ..writeln('// ignore_for_file: prefer_single_quotes')
    ..writeln(
      'const h5DateSymbols = <String, Map<String, dynamic>>${literal({for (final language in languages) language: symbols[language]!.serializeToMap()})};',
    )
    ..writeln(
      'const h5DatePatterns = <String, Map<String, String>>${literal({for (final language in languages) language: patterns[language]!})};',
    );
  await File('lib/app/date_data.dart').writeAsString(output.toString());
}
